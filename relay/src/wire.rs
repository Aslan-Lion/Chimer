//! The relay envelope: `relay/1`.
//!
//! This is a **transport** protocol, not an application protocol. It carries the
//! Milestone 6 host/device messages as opaque `payload` objects and never
//! interprets them. The relay therefore cannot start a timer, cannot read a
//! preset, and cannot mint a credential, whatever a client sends.
//!
//! The envelope is versioned separately (`RELAY_PROTOCOL`) from the application
//! protocol the payloads speak, so the two can evolve independently: the relay
//! is expected to run for a long time without being redeployed when the desktop
//! application changes.
//!
//! Keep-alive is done with WebSocket **control** frames (the relay sends `ping`
//! and every conforming client answers `pong` automatically), plus an idle read
//! timeout. There are deliberately no JSON heartbeat messages: the application
//! protocol already has its own `{ "type": "ping" }`, and it flows through as
//! ordinary data.

use serde::{Deserialize, Serialize};
use serde_json::Value;

/// Version of the relay envelope.
pub const RELAY_PROTOCOL: u32 = 1;

/// Prefix every host identifier generated by the desktop application carries.
pub const HOST_ID_PREFIX: &str = "h-";

/// Shortest and longest acceptable host identifier, prefix included.
pub const MIN_HOST_ID_LEN: usize = 8;
pub const MAX_HOST_ID_LEN: usize = 64;

/// Entropy in a route identifier. 256 bits: a route cannot be guessed, so one
/// device can never address another device's traffic.
pub const ROUTE_ID_BYTES: usize = 32;

/// Length of a route identifier once base64url-encoded without padding.
pub const ROUTE_ID_LEN: usize = 43;

/// Stable error codes. Disjoint from the application protocol's codes on
/// purpose, so a relay failure and a host refusal never look alike in the
/// remote interface.
pub mod codes {
    pub const MALFORMED: &str = "malformed";
    pub const TOO_LARGE: &str = "too-large";
    pub const UNSUPPORTED_PROTOCOL: &str = "unsupported-protocol";
    pub const UNAUTHORIZED_HOST: &str = "unauthorized-host";
    pub const HOST_CONFLICT: &str = "host-conflict";
    pub const UNKNOWN_HOST: &str = "unknown-host";
    pub const HOST_OFFLINE: &str = "host-offline";
    pub const RATE_LIMITED: &str = "rate-limited";
    pub const LIMIT_EXCEEDED: &str = "limit-exceeded";
    pub const SHUTTING_DOWN: &str = "shutting-down";
    pub const INTERNAL: &str = "internal";
}

/// True when `id` has the shape the desktop application generates.
pub fn valid_host_id(id: &str) -> bool {
    if id.len() < MIN_HOST_ID_LEN || id.len() > MAX_HOST_ID_LEN {
        return false;
    }
    let Some(tail) = id.strip_prefix(HOST_ID_PREFIX) else {
        return false;
    };
    !tail.is_empty()
        && tail
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

/// True when `id` is exactly one base64url route identifier.
pub fn valid_route_id(id: &str) -> bool {
    id.len() == ROUTE_ID_LEN
        && id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

/// A peer as the relay observed it.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct Peer {
    /// The source address of the device's connection to the relay.
    pub address: String,
}

// ---------------------------------------------------------------------------
// Host leg
// ---------------------------------------------------------------------------

/// Everything a host may send to the relay.
#[derive(Debug, Deserialize)]
#[serde(tag = "t", rename_all = "kebab-case")]
pub enum HostInbound {
    /// First frame on the host socket.
    #[serde(rename_all = "camelCase")]
    Hello {
        #[serde(default = "relay_protocol")]
        protocol: u32,
        host_id: String,
        host_token: String,
    },
    /// An application message destined for one device.
    #[serde(rename_all = "camelCase")]
    Data { route: String, payload: Value },
    /// The host finished with a route (for example a device it just revoked).
    #[serde(rename_all = "camelCase")]
    Close { route: String, reason: Option<String> },
}

fn relay_protocol() -> u32 {
    RELAY_PROTOCOL
}

/// Everything the relay may send to a host.
///
/// `Deserialize` as well as `Serialize` so the transport tests can read the
/// bytes the relay actually put on the socket.
#[derive(Debug, Serialize, Deserialize)]
#[serde(tag = "t", rename_all = "kebab-case")]
pub enum HostOutbound {
    #[serde(rename_all = "camelCase")]
    Ready {
        protocol: u32,
        host_id: String,
    },
    /// A device connected and was given `route`.
    #[serde(rename_all = "camelCase")]
    Open {
        route: String,
        peer: Peer,
        user_agent: Option<String>,
    },
    #[serde(rename_all = "camelCase")]
    Data { route: String, payload: Value },
    /// A device went away, or the relay let it go.
    #[serde(rename_all = "camelCase")]
    Closed { route: String, reason: String },
    Error { code: String, message: String },
}

// ---------------------------------------------------------------------------
// Device leg
// ---------------------------------------------------------------------------

/// Everything a device may send to the relay.
#[derive(Debug, Deserialize)]
#[serde(tag = "t", rename_all = "kebab-case")]
pub enum DeviceInbound {
    /// First frame on the device socket. The host id is in the path.
    Hello {
        #[serde(default = "relay_protocol")]
        protocol: u32,
    },
    /// An application message destined for the host it is attached to.
    Data { payload: Value },
}

/// Everything the relay may send to a device.
///
/// `Deserialize` as well as `Serialize` so the transport tests can read the
/// bytes the relay actually put on the socket.
#[derive(Debug, Serialize, Deserialize)]
#[serde(tag = "t", rename_all = "kebab-case")]
pub enum DeviceOutbound {
    #[serde(rename_all = "camelCase")]
    Ready {
        protocol: u32,
        route: String,
        host_id: String,
        host_online: bool,
    },
    Data { payload: Value },
    Error { code: String, message: String },
    /// The relay is closing this device's route on the host's behalf.
    Shutdown { reason: String },
}

impl HostOutbound {
    pub fn error(code: &str, message: impl Into<String>) -> HostOutbound {
        HostOutbound::Error {
            code: code.to_string(),
            message: message.into(),
        }
    }
}

impl DeviceOutbound {
    pub fn error(code: &str, message: impl Into<String>) -> DeviceOutbound {
        DeviceOutbound::Error {
            code: code.to_string(),
            message: message.into(),
        }
    }
}

/// Serialises an outbound envelope. The message is built from JSON values, so
/// encoding cannot fail; the fallback keeps the transport total rather than
/// panicking inside a connection task.
pub fn to_text<T: Serialize>(message: &T) -> String {
    serde_json::to_string(message).unwrap_or_else(|_| {
        format!(
            r#"{{"t":"error","code":"{}","message":"The relay could not encode that message."}}"#,
            codes::INTERNAL
        )
    })
}

/// Parses one inbound envelope.
pub fn parse<'a, T: Deserialize<'a>>(text: &'a str) -> Result<T, String> {
    serde_json::from_str(text).map_err(|error| error.to_string())
}

/// True when a payload is a JSON object within `limit` bytes.
///
/// The relay enforces this on every forwarded frame so a device cannot use the
/// relay to deliver something the host would have refused on the LAN, and so a
/// relay cannot be turned into a memory amplifier.
pub fn payload_within(payload: &Value, limit: usize) -> bool {
    if !payload.is_object() {
        return false;
    }
    serde_json::to_vec(payload).is_ok_and(|encoded| encoded.len() <= limit)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn a_generated_host_id_is_accepted() {
        assert!(valid_host_id("h-abcdefgh"));
        assert!(valid_host_id("h-Qm9vYmFyZGlhbmRfdG9rZW4"));
        assert!(valid_host_id("h-with-dash-and_underscore"));
    }

    #[test]
    fn a_host_id_must_carry_the_prefix_and_be_sane() {
        for bad in [
            "",
            "h-",
            "abcdefgh",                              // no prefix
            "h-short",                               // too short
            &format!("h-{}", "x".repeat(100)),       // too long
            "h-has space",
            "h-has/slash",
            "h-has.dot",
            "H-ABCDEFGH",                            // prefix is lower case
        ] {
            assert!(!valid_host_id(bad), "{bad:?} must be refused");
        }
    }

    #[test]
    fn a_route_id_is_exactly_one_base64url_word() {
        assert!(valid_route_id(&"a".repeat(ROUTE_ID_LEN)));
        assert!(valid_route_id(&"ABCdef012-_".repeat(4)[..ROUTE_ID_LEN]));
        assert!(!valid_route_id(""));
        assert!(!valid_route_id(&"a".repeat(ROUTE_ID_LEN - 1)));
        assert!(!valid_route_id(&"a".repeat(ROUTE_ID_LEN + 1)));
        assert!(!valid_route_id(&"!".repeat(ROUTE_ID_LEN)));
    }

    #[test]
    fn a_host_hello_round_trips() {
        let raw = r#"{"t":"hello","protocol":1,"hostId":"h-abcdefgh","hostToken":"s3cret-value-here"}"#;
        let parsed: HostInbound = parse(raw).unwrap();
        match parsed {
            HostInbound::Hello {
                protocol,
                host_id,
                host_token,
            } => {
                assert_eq!(protocol, RELAY_PROTOCOL);
                assert_eq!(host_id, "h-abcdefgh");
                assert_eq!(host_token, "s3cret-value-here");
            }
            other => panic!("expected a hello, got {other:?}"),
        }
    }

    #[test]
    fn a_hello_without_a_version_is_treated_as_this_one() {
        let parsed: HostInbound = parse(r#"{"t":"hello","hostId":"h-a","hostToken":"b"}"#).unwrap();
        assert!(matches!(parsed, HostInbound::Hello { protocol, .. } if protocol == RELAY_PROTOCOL));
    }

    #[test]
    fn an_unknown_envelope_type_is_refused() {
        assert!(parse::<HostInbound>(r#"{"t":"upgrade"}"#).is_err());
        assert!(parse::<DeviceInbound>(r#"{"t":"shutdown"}"#).is_err());
    }

    #[test]
    fn the_host_data_envelope_carries_a_route() {
        let raw = r#"{"t":"data","route":"abc","payload":{"type":"state","revision":4}}"#;
        let parsed: HostInbound = parse(raw).unwrap();
        match parsed {
            HostInbound::Data { route, payload } => {
                assert_eq!(route, "abc");
                assert_eq!(payload["revision"], json!(4));
            }
            other => panic!("expected data, got {other:?}"),
        }
    }

    #[test]
    fn the_device_data_envelope_has_no_route() {
        let raw = r#"{"t":"data","payload":{"type":"command","id":"c-1"}}"#;
        let parsed: DeviceInbound = parse(raw).unwrap();
        match parsed {
            DeviceInbound::Data { payload } => assert_eq!(payload["id"], json!("c-1")),
            other => panic!("expected data, got {other:?}"),
        }
    }

    #[test]
    fn outbound_envelopes_serialise_with_camel_case_fields() {
        let open = HostOutbound::Open {
            route: "r".to_string(),
            peer: Peer {
                address: "203.0.113.9:443".to_string(),
            },
            user_agent: Some("ua".to_string()),
        };
        let json = to_text(&open);
        assert!(json.contains(r#""t":"open""#), "{json}");
        assert!(json.contains(r#""userAgent":"ua""#), "{json}");

        let ready = DeviceOutbound::Ready {
            protocol: RELAY_PROTOCOL,
            route: "r".to_string(),
            host_id: "h-abcdefgh".to_string(),
            host_online: true,
        };
        let json = to_text(&ready);
        assert!(json.contains(r#""hostId":"h-abcdefgh""#), "{json}");
        assert!(json.contains(r#""hostOnline":true"#), "{json}");
    }

    #[test]
    fn an_error_envelope_is_well_formed() {
        let json = to_text(&DeviceOutbound::error(codes::HOST_OFFLINE, "The host is not online."));
        assert!(!json.contains("\"type\""), "the tag is 't', not 'type': {json}");
        assert!(json.contains(r#""t":"error""#), "{json}");
        assert!(json.contains(r#""code":"host-offline""#), "{json}");
    }

    #[test]
    fn a_payload_must_be_an_object_within_the_limit() {
        assert!(payload_within(&json!({"type":"ping"}), 64));
        assert!(!payload_within(&json!("a bare string"), 64));
        assert!(!payload_within(&json!([1, 2, 3]), 64));
        assert!(!payload_within(&json!({"big":"x".repeat(100)}), 64));
    }

    #[test]
    fn relay_error_codes_never_collide_with_application_codes() {
        // A short guard against someone later reusing an application code here.
        for application_code in [
            "unauthenticated",
            "forbidden",
            "timer-active",
            "revoked",
            "unknown-action",
            "invalid-payload",
        ] {
            assert!(
                ![
                    codes::MALFORMED,
                    codes::TOO_LARGE,
                    codes::UNSUPPORTED_PROTOCOL,
                    codes::UNAUTHORIZED_HOST,
                    codes::HOST_CONFLICT,
                    codes::UNKNOWN_HOST,
                    codes::HOST_OFFLINE,
                    codes::RATE_LIMITED,
                    codes::LIMIT_EXCEEDED,
                    codes::SHUTTING_DOWN,
                    codes::INTERNAL,
                ]
                .contains(&application_code),
                "{application_code} is an application code"
            );
        }
    }
}
